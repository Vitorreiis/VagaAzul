
CREATE TABLE bairro (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE trecho (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        id_bairro BIGINT NOT NULL,
                        logradouro VARCHAR(200) NOT NULL,
                        quantidade_total_vagas INTEGER NOT NULL,
                        latitude NUMERIC(10, 7),
                        longitude NUMERIC(10, 7),

                        CONSTRAINT fk_trecho_bairro
                            FOREIGN KEY (id_bairro)
                                REFERENCES bairro(id),

                        CONSTRAINT chk_trecho_quantidade_vagas
                            CHECK (quantidade_total_vagas > 0),

                        CONSTRAINT chk_trecho_latitude
                            CHECK (latitude BETWEEN -90 AND 90),

                        CONSTRAINT chk_trecho_longitude
                            CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE ocupacao_simulada (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   id_trecho BIGINT NOT NULL UNIQUE,
                                   vagas_ocupadas INTEGER NOT NULL,
                                   atualizado_em TIMESTAMP(6) NOT NULL,

                                   CONSTRAINT fk_ocupacao_trecho
                                       FOREIGN KEY (id_trecho)
                                           REFERENCES trecho(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT chk_ocupacao_vagas
                                       CHECK (vagas_ocupadas >= 0)
);
